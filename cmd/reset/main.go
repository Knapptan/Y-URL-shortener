// Command reset генерирует методы Reset() для структур,
// помеченных комментарием // generate:reset.
//
// Использование:
//
//	go run ./cmd/reset            # сканировать текущий модуль (./...)
//	go run ./cmd/reset -dir=/path # сканировать указанный корень
//
// Генерация для всего проекта одной командой:
//
//	go generate ./cmd/reset
package main

//go:generate go run . -dir=../..

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"go/types"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

// resetMarker — комментарий, которым помечаются структуры,
// для которых нужно сгенерировать метод Reset().
const resetMarker = "generate:reset"

// fieldInfo описывает одно поле структуры: его имя и тип.
type fieldInfo struct {
	name string
	typ  types.Type
}

// target описывает структуру, для которой генерируется метод Reset().
type target struct {
	name   string
	fields []fieldInfo
}

// main разбирает флаги командной строки и запускает генерацию.
func main() {
	root := flag.String("dir", ".", "корневая директория для сканирования")
	flag.Parse()
	if err := run(*root); err != nil {
		log.Fatal(err)
	}
}

// run загружает все пакеты начиная с root и обрабатывает каждый.
func run(root string) error {
	abs, err := filepath.Abs(root)
	if err != nil {
		return err
	}

	// Настраиваем загрузчик: нужны имена, файлы, AST, типы и TypesInfo.
	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax |
			packages.NeedTypes | packages.NeedTypesInfo,
		Dir:   abs,
		Tests: false,
	}

	pkgs, err := packages.Load(cfg, "./...")
	if err != nil {
		return err
	}
	if n := packages.PrintErrors(pkgs); n > 0 {
		return fmt.Errorf("packages.Load: %d ошибок", n)
	}

	for _, pkg := range pkgs {
		if err := processPackage(pkg); err != nil {
			return fmt.Errorf("%s: %w", pkg.PkgPath, err)
		}
	}
	return nil
}

// processPackage ищет структуры с маркером // generate:reset
// и генерирует для них файл reset.gen.go в директории пакета.
func processPackage(pkg *packages.Package) error {
	targets := make(map[string]*target)
	marked := make(map[types.Type]bool)

	// 1. Обходим AST и собираем структуры с маркером.
	for _, file := range pkg.Syntax {
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			for _, spec := range gen.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok || !hasMarker(gen, ts) {
					continue
				}
				// Интересуют только структуры.
				if _, ok := ts.Type.(*ast.StructType); !ok {
					continue
				}
				obj := pkg.TypesInfo.Defs[ts.Name]
				if obj == nil {
					continue
				}
				structType, ok := obj.Type().Underlying().(*types.Struct)
				if !ok {
					continue
				}
				t := &target{name: ts.Name.Name}
				// Сохраняем поля для генерации сброса.
				for i := 0; i < structType.NumFields(); i++ {
					f := structType.Field(i)
					t.fields = append(t.fields, fieldInfo{name: f.Name(), typ: f.Type()})
				}
				targets[ts.Name.Name] = t
				marked[obj.Type()] = true
			}
		}
	}

	// Нет структур с маркером — нечего генерировать.
	if len(targets) == 0 {
		return nil
	}

	var pkgDir string
	if len(pkg.GoFiles) > 0 {
		pkgDir = filepath.Dir(pkg.GoFiles[0])
	}
	if pkgDir == "" {
		return nil
	}

	// 2. Формируем содержимое reset.gen.go.
	buf := &bytes.Buffer{}
	fmt.Fprintf(buf, "// Code generated by reset generator; DO NOT EDIT.\n\n")
	fmt.Fprintf(buf, "package %s\n\n", pkg.Name)

	// Сортируем имена для детерминированного вывода.
	names := make([]string, 0, len(targets))
	for name := range targets {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		writeResetMethod(buf, targets[name], marked)
	}

	// Форматируем итоговый файл стандартным gofmt.
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format: %w\n---\n%s", err, buf.String())
	}

	return os.WriteFile(filepath.Join(pkgDir, "reset.gen.go"), src, 0o644)
}

// hasMarker проверяет, есть ли над объявлением комментарий // generate:reset.
func hasMarker(gen *ast.GenDecl, ts *ast.TypeSpec) bool {
	for _, doc := range []*ast.CommentGroup{gen.Doc, ts.Doc} {
		if doc == nil {
			continue
		}
		for _, c := range doc.List {
			if strings.TrimSpace(strings.TrimPrefix(c.Text, "//")) == resetMarker {
				return true
			}
		}
	}
	return false
}

// writeResetMethod генерирует метод Reset() для одной структуры.
func writeResetMethod(buf *bytes.Buffer, t *target, marked map[types.Type]bool) {
	fmt.Fprintf(buf, "// Reset resets %s to its zero state.\n", t.name)
	fmt.Fprintf(buf, "func (r *%s) Reset() {\n", t.name)
	// Защита от nil-приёмника.
	buf.WriteString("\tif r == nil {\n\t\treturn\n\t}\n")
	for _, f := range t.fields {
		writeFieldReset(buf, "\t", "r."+f.name, f.typ, marked)
	}
	buf.WriteString("}\n\n")
}

// writeFieldReset генерирует код сброса одного поля.
// indent — отступ, accessor — выражение доступа к полю (например, r.Field).
func writeFieldReset(buf *bytes.Buffer, indent, accessor string, typ types.Type, marked map[types.Type]bool) {
	switch u := typ.Underlying().(type) {
	case *types.Basic:
		// Примитивы: int → 0, string → "", bool → false.
		fmt.Fprintf(buf, "%s%s = %s\n", indent, accessor, zeroLiteral(u))
	case *types.Slice:
		// Слайсы обрезаем по длине, не зануляя.
		fmt.Fprintf(buf, "%s%s = %s[:0]\n", indent, accessor, accessor)
	case *types.Map:
		// Мапы очищаем встроенной функцией clear.
		fmt.Fprintf(buf, "%sclear(%s)\n", indent, accessor)
	case *types.Interface:
		// Интерфейсы обнуляем.
		fmt.Fprintf(buf, "%s%s = nil\n", indent, accessor)
	case *types.Pointer:
		// Указатели: если не nil — сбрасываем значение по адресу.
		fmt.Fprintf(buf, "%sif %s != nil {\n", indent, accessor)
		writeDerefReset(buf, indent+"\t", "*"+accessor, u.Elem(), marked)
		fmt.Fprintf(buf, "%s}\n", indent)
	case *types.Struct:
		// Вложенная структура: если у неё есть Reset() — вызываем,
		// иначе присваиваем нулевое значение.
		if hasResetMethod(typ, marked) {
			fmt.Fprintf(buf, "%s%s.Reset()\n", indent, accessor)
		} else {
			fmt.Fprintf(buf, "%s%s = %s{}\n", indent, accessor, typ.String())
		}
	case *types.Array:
		// Массивы заменяем нулевым значением.
		fmt.Fprintf(buf, "%s%s = %s{}\n", indent, accessor, typ.String())
	default:
		fmt.Fprintf(buf, "%s%s = nil\n", indent, accessor)
	}
}

// writeDerefReset генерирует сброс значения по указателю (выражение expr).
// Используется для полей-указателей: обрабатываем тип, на который указывает указатель.
func writeDerefReset(buf *bytes.Buffer, indent, expr string, elem types.Type, marked map[types.Type]bool) {
	switch u := elem.Underlying().(type) {
	case *types.Basic:
		fmt.Fprintf(buf, "%s%s = %s\n", indent, expr, zeroLiteral(u))
	case *types.Slice:
		fmt.Fprintf(buf, "%s%s = %s[:0]\n", indent, expr, expr)
	case *types.Map:
		fmt.Fprintf(buf, "%sclear(%s)\n", indent, expr)
	case *types.Interface:
		fmt.Fprintf(buf, "%s%s = nil\n", indent, expr)
	case *types.Struct:
		if hasResetMethod(types.NewPointer(elem), marked) {
			fmt.Fprintf(buf, "%s%s.Reset()\n", indent, expr)
		} else {
			fmt.Fprintf(buf, "%s%s = %s{}\n", indent, expr, elem.String())
		}
	case *types.Array:
		fmt.Fprintf(buf, "%s%s = %s{}\n", indent, expr, elem.String())
	default:
		fmt.Fprintf(buf, "%s%s = nil\n", indent, expr)
	}
}

// zeroLiteral возвращает литерал нулевого значения для примитивного типа.
func zeroLiteral(b *types.Basic) string {
	info := b.Info()
	switch {
	case info&types.IsBoolean != 0:
		return "false"
	case info&types.IsString != 0:
		return `""`
	case info&types.IsNumeric != 0:
		return "0"
	}
	return "nil"
}

// hasResetMethod проверяет, будет ли у типа метод Reset()
// (сгенерированный в этом же прогоне или уже существующий).
func hasResetMethod(typ types.Type, marked map[types.Type]bool) bool {
	// Тип, помеченный generate:reset, точно получит Reset().
	if marked[typ] {
		return true
	}
	if ptr, ok := typ.(*types.Pointer); ok && marked[ptr.Elem()] {
		return true
	}
	// Иначе ищем уже существующий метод Reset() у типа.
	obj, _, _ := types.LookupFieldOrMethod(typ, true, nil, "Reset")
	if obj == nil {
		return false
	}
	fn, ok := obj.(*types.Func)
	if !ok {
		return false
	}
	sig, ok := fn.Type().(*types.Signature)
	if !ok {
		return false
	}
	return sig.Params().Len() == 0 && sig.Results().Len() == 0
}
