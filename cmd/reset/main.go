// Command reset генерирует методы Reset() для структур,
// помеченных комментарием // generate:reset.
//
// Использование:
//
//	go run ./cmd/reset            # сканировать текущий модуль (./...)
//	go run ./cmd/reset -dir=/path # сканировать указанный корень
//
// Генерация для всего проекта одной командой:
//
//	go generate ./cmd/reset
package main

//go:generate go run . -dir=../..

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"go/types"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

const resetMarker = "generate:reset"

type fieldInfo struct {
	name string
	typ  types.Type
}

type target struct {
	name   string
	fields []fieldInfo
}

// genCtx хранит контекст генерации для одного пакета.
// pkg — текущий пакет (чтобы отличать «свои» типы от чужих);
// imports — накопленные импорты (simple name → import path).
type genCtx struct {
	pkg     *types.Package
	imports map[string]string
}

// typeString возвращает строку типа, готовую к вставке в сгенерированный
// код: для типов текущего пакета — простое имя без квалификатора,
// для типов из других пакетов — qualified name (pkg.Name()) с
// автоматической регистрацией импорта в ctx.imports.
//
// Это исправляет проблему, когда typ.String() выдавал полный путь
// пакета (github.com/.../model.MyStruct), а import-блок в reset.gen.go
// отсутствовал.
func (g *genCtx) typeString(typ types.Type) string {
	return types.TypeString(typ, func(p *types.Package) string {
		if p == nil || p == g.pkg {
			return "" // same package — без квалификатора
		}
		g.imports[p.Name()] = p.Path()
		return p.Name()
	})
}

func main() {
	root := flag.String("dir", ".", "корневая директория для сканирования")
	flag.Parse()
	if err := run(*root); err != nil {
		log.Fatal(err)
	}
}

func run(root string) error {
	abs, err := filepath.Abs(root)
	if err != nil {
		return err
	}

	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedSyntax |
			packages.NeedTypes | packages.NeedTypesInfo,
		Dir:   abs,
		Tests: false,
	}

	pkgs, err := packages.Load(cfg, "./...")
	if err != nil {
		return err
	}
	if n := packages.PrintErrors(pkgs); n > 0 {
		return fmt.Errorf("packages.Load: %d ошибок", n)
	}

	for _, pkg := range pkgs {
		if err := processPackage(pkg); err != nil {
			return fmt.Errorf("%s: %w", pkg.PkgPath, err)
		}
	}
	return nil
}

func processPackage(pkg *packages.Package) error {
	targets := make(map[string]*target)
	marked := make(map[types.Type]bool)

	for _, file := range pkg.Syntax {
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			for _, spec := range gen.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok || !hasMarker(gen, ts) {
					continue
				}
				if _, ok := ts.Type.(*ast.StructType); !ok {
					continue
				}
				obj := pkg.TypesInfo.Defs[ts.Name]
				if obj == nil {
					continue
				}
				structType, ok := obj.Type().Underlying().(*types.Struct)
				if !ok {
					continue
				}
				t := &target{name: ts.Name.Name}
				for i := 0; i < structType.NumFields(); i++ {
					f := structType.Field(i)
					t.fields = append(t.fields, fieldInfo{name: f.Name(), typ: f.Type()})
				}
				targets[ts.Name.Name] = t
				marked[obj.Type()] = true
			}
		}
	}

	if len(targets) == 0 {
		return nil
	}

	var pkgDir string
	if len(pkg.GoFiles) > 0 {
		pkgDir = filepath.Dir(pkg.GoFiles[0])
	}
	if pkgDir == "" {
		return nil
	}

	ctx := &genCtx{
		pkg:     pkg.Types,
		imports: make(map[string]string),
	}

	// Тело генерируем во временный буфер: импорты собираются по ходу.
	body := &bytes.Buffer{}
	names := make([]string, 0, len(targets))
	for name := range targets {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		writeResetMethod(body, targets[name], marked, ctx)
	}

	// Теперь формируем итоговый файл: заголовок, package, imports, тело.
	// Это гарантирует, что import-блок идёт до объявлений (требование Go)
	// и что в нём есть все пакеты, использованные в typeString.
	final := &bytes.Buffer{}
	fmt.Fprintf(final, "// Code generated by reset generator; DO NOT EDIT.\n\n")
	fmt.Fprintf(final, "package %s\n\n", pkg.Name)

	if len(ctx.imports) > 0 {
		paths := make([]string, 0, len(ctx.imports))
		for _, p := range ctx.imports {
			paths = append(paths, p)
		}
		sort.Strings(paths)
		fmt.Fprintf(final, "import (\n")
		for _, p := range paths {
			fmt.Fprintf(final, "\t%q\n", p)
		}
		fmt.Fprintf(final, ")\n\n")
	}
	final.Write(body.Bytes())

	src, err := format.Source(final.Bytes())
	if err != nil {
		return fmt.Errorf("format: %w\n---\n%s", err, final.String())
	}

	return os.WriteFile(filepath.Join(pkgDir, "reset.gen.go"), src, 0o644)
}

func hasMarker(gen *ast.GenDecl, ts *ast.TypeSpec) bool {
	for _, doc := range []*ast.CommentGroup{gen.Doc, ts.Doc} {
		if doc == nil {
			continue
		}
		for _, c := range doc.List {
			if strings.TrimSpace(strings.TrimPrefix(c.Text, "//")) == resetMarker {
				return true
			}
		}
	}
	return false
}

func writeResetMethod(buf *bytes.Buffer, t *target, marked map[types.Type]bool, ctx *genCtx) {
	fmt.Fprintf(buf, "// Reset resets %s to its zero state.\n", t.name)
	fmt.Fprintf(buf, "func (r *%s) Reset() {\n", t.name)
	buf.WriteString("\tif r == nil {\n\t\treturn\n\t}\n")
	for _, f := range t.fields {
		writeFieldReset(buf, "\t", "r."+f.name, f.typ, marked, ctx)
	}
	buf.WriteString("}\n\n")
}

func writeFieldReset(buf *bytes.Buffer, indent, accessor string, typ types.Type, marked map[types.Type]bool, ctx *genCtx) {
	switch u := typ.Underlying().(type) {
	case *types.Basic:
		fmt.Fprintf(buf, "%s%s = %s\n", indent, accessor, zeroLiteral(u))
	case *types.Slice:
		fmt.Fprintf(buf, "%s%s = %s[:0]\n", indent, accessor, accessor)
	case *types.Map:
		fmt.Fprintf(buf, "%sclear(%s)\n", indent, accessor)
	case *types.Interface:
		fmt.Fprintf(buf, "%s%s = nil\n", indent, accessor)
	case *types.Pointer:
		fmt.Fprintf(buf, "%sif %s != nil {\n", indent, accessor)
		writeDerefReset(buf, indent+"\t", "*"+accessor, u.Elem(), marked, ctx)
		fmt.Fprintf(buf, "%s}\n", indent)
	case *types.Struct:
		if hasResetMethod(typ, marked) {
			fmt.Fprintf(buf, "%s%s.Reset()\n", indent, accessor)
		} else {
			// typeString вместо typ.String() — иначе полный путь пакета
			// и никаких imports.
			fmt.Fprintf(buf, "%s%s = %s{}\n", indent, accessor, ctx.typeString(typ))
		}
	case *types.Array:
		fmt.Fprintf(buf, "%s%s = %s{}\n", indent, accessor, ctx.typeString(typ))
	default:
		fmt.Fprintf(buf, "%s%s = nil\n", indent, accessor)
	}
}

func writeDerefReset(buf *bytes.Buffer, indent, expr string, elem types.Type, marked map[types.Type]bool, ctx *genCtx) {
	switch u := elem.Underlying().(type) {
	case *types.Basic:
		fmt.Fprintf(buf, "%s%s = %s\n", indent, expr, zeroLiteral(u))
	case *types.Slice:
		fmt.Fprintf(buf, "%s%s = %s[:0]\n", indent, expr, expr)
	case *types.Map:
		fmt.Fprintf(buf, "%sclear(%s)\n", indent, expr)
	case *types.Interface:
		fmt.Fprintf(buf, "%s%s = nil\n", indent, expr)
	case *types.Struct:
		if hasResetMethod(types.NewPointer(elem), marked) {
			fmt.Fprintf(buf, "%s%s.Reset()\n", indent, expr)
		} else {
			fmt.Fprintf(buf, "%s%s = %s{}\n", indent, expr, ctx.typeString(elem))
		}
	case *types.Array:
		fmt.Fprintf(buf, "%s%s = %s{}\n", indent, expr, ctx.typeString(elem))
	default:
		fmt.Fprintf(buf, "%s%s = nil\n", indent, expr)
	}
}

func zeroLiteral(b *types.Basic) string {
	info := b.Info()
	switch {
	case info&types.IsBoolean != 0:
		return "false"
	case info&types.IsString != 0:
		return `""`
	case info&types.IsNumeric != 0:
		return "0"
	}
	return "nil"
}

func hasResetMethod(typ types.Type, marked map[types.Type]bool) bool {
	if marked[typ] {
		return true
	}
	if ptr, ok := typ.(*types.Pointer); ok && marked[ptr.Elem()] {
		return true
	}
	obj, _, _ := types.LookupFieldOrMethod(typ, true, nil, "Reset")
	if obj == nil {
		return false
	}
	fn, ok := obj.(*types.Func)
	if !ok {
		return false
	}
	sig, ok := fn.Type().(*types.Signature)
	if !ok {
		return false
	}
	return sig.Params().Len() == 0 && sig.Results().Len() == 0
}
