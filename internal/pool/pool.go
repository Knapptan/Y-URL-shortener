// Package pool предоставляет generic-контейнер для повторного
// использования «тяжёлых» объектов, реализующих метод Reset().
//
// Идея та же, что и у sync.Pool, но с типобезопасностью и
// автоматическим вызовом Reset() перед возвратом объекта в пул.
package pool

import "sync"

// Resettable — ограничение типа: любой объект, у которого есть метод
// Reset(). Такой метод должен приводить объект к начальному состоянию,
// чтобы его можно было безопасно переиспользовать.
type Resettable interface {
	Reset()
}

// Pool — типобезопасный пул объектов с автоматическим сбросом.
// Хранит объекты конкретного типа T, реализующего Reset().
type Pool[T Resettable] struct {
	sp sync.Pool
}

// New создаёт и возвращает указатель на новый Pool.
// Параметр newFn — функция-фабрика, которая создаёт новый объект T.
// Она вызывается, когда пул пуст и нужно вернуть объект.
func New[T Resettable](newFn func() T) *Pool[T] {
	return &Pool[T]{
		sp: sync.Pool{
			New: func() any {
				return newFn()
			},
		},
	}
}

// Get возвращает объект из пула.
// Если пул пуст, вызывается фабрика, переданная в New.
// Перед возвратом объекта его состояние НЕ сбрасывается —
// Reset() вызывается в Put() при возврате объекта в пул.
func (p *Pool[T]) Get() T {
	return p.sp.Get().(T)
}

// Put помещает объект в пул.
// Перед возвратом вызывается Reset(), чтобы объект был в начальном
// состоянии к моменту следующего Get.
func (p *Pool[T]) Put(v T) {
	v.Reset()
	p.sp.Put(v)
}
